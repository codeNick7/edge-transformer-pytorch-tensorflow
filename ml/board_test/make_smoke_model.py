#!/usr/bin/env python3
"""Build the TFLite Micro smoke-test model for the UNO Q MCU (P0 Phase 0, route A).

Not the transformer. A tiny Keras MLP (4 -> 16 ReLU -> 3 softmax) trained on the real
sept15 soil features, using only FULLY_CONNECTED + SOFTMAX, the two ops EloquentTinyML's
own Iris example uses. Purpose: prove TFLite Micro compiles, links and gives the same
answers on the board as on the Mac.

Writes ml/board_test/tflm_smoke/sketch/model.h with:
  * the .tflite flatbuffer as an aligned byte array (EloquentTinyML format)
  * TF_NUM_OPS / TF_NUM_INPUTS / TF_NUM_OUTPUTS / TF_OP_* macros
  * N_SAMPLES pre-normalised test inputs, the class and probabilities the Mac's TFLite
    interpreter produced for each, so the sketch can print PASS/FAIL per sample

Usage:
  .venv/bin/python ml/board_test/make_smoke_model.py data-local/datasets/sept15.jsonl
"""

from __future__ import annotations

import json
import os
import sys

import numpy as np

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")
import tensorflow as tf  # noqa: E402

_HERE = os.path.dirname(os.path.abspath(__file__))
FEATURES = ["rsmi", "light_delta", "gas_index_trend", "rsmi_trend"]
CLASSES = ["soil_health_degrading", "stable", "waterlogged_risk"]
N_TRAIN = 200_000
SAMPLES_PER_CLASS = 2


def load(path: str, meta: dict):
    X, y = [], []
    with open(path) as f:
        for line in f:
            r = json.loads(line)
            X.append([r[k] for k in FEATURES])
            y.append(CLASSES.index(r["label"]))
    X, y = np.asarray(X, np.float32), np.asarray(y, np.int64)
    s = meta["split_index"]
    return X[:s], y[:s], X[s:], y[s:]


def c_floats(v) -> str:
    return ", ".join(f"{float(x):.8f}f" for x in v)


def main() -> None:
    dataset = sys.argv[1]
    meta = json.load(open(dataset.replace(".jsonl", ".meta.json")))
    Xtr, ytr, Xte, yte = load(dataset, meta)

    rng = np.random.default_rng(0)
    idx = rng.choice(len(ytr), size=min(N_TRAIN, len(ytr)), replace=False)
    mean, std = Xtr[idx].mean(0), Xtr[idx].std(0) + 1e-6
    norm = lambda a: ((a - mean) / std).astype(np.float32)  # noqa: E731

    tf.keras.utils.set_random_seed(0)
    model = tf.keras.Sequential([
        tf.keras.Input(shape=(4,)),
        tf.keras.layers.Dense(16, activation="relu"),
        tf.keras.layers.Dense(3),
        tf.keras.layers.Softmax(),
    ])
    model.compile(optimizer=tf.keras.optimizers.Adam(0.01), loss="sparse_categorical_crossentropy", metrics=["accuracy"])
    model.fit(norm(Xtr[idx]), ytr[idx], epochs=5, batch_size=1024, verbose=0)
    _, test_acc = model.evaluate(norm(Xte), yte, batch_size=8192, verbose=0)
    print(f"smoke MLP: {model.count_params()} params, test accuracy {test_acc:.4f} (not the point of this model)")

    tflite = tf.lite.TFLiteConverter.from_keras_model(model).convert()
    interp = tf.lite.Interpreter(
        model_content=tflite,
        experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_REF,  # reference kernels, no XNNPACK delegate (closest to TFLM)
    )
    interp.allocate_tensors()
    ops = sorted({op["op_name"] for op in interp._get_ops_details()})
    print(f"TFLite ops: {ops}; size {len(tflite)} bytes")
    assert set(ops) <= {"FULLY_CONNECTED", "SOFTMAX"}, f"unexpected ops for the smoke test: {ops}"

    inp, out = interp.get_input_details()[0], interp.get_output_details()[0]
    samples, expected_cls, expected_prob, true_cls = [], [], [], []
    for c in range(3):
        for j in np.where(yte == c)[0][rng.permutation((yte == c).sum())][: SAMPLES_PER_CLASS * 20]:
            x = norm(Xte[j:j + 1])
            interp.set_tensor(inp["index"], x)
            interp.invoke()
            p = interp.get_tensor(out["index"])[0]
            if int(p.argmax()) == c:  # pick samples the model gets right, so a board mismatch is unambiguous
                samples.append(x[0]); expected_cls.append(int(p.argmax())); expected_prob.append(p); true_cls.append(c)
            if sum(1 for t in true_cls if t == c) == SAMPLES_PER_CLASS:
                break

    n = len(samples)
    body = ", ".join(f"0x{b:02x}" for b in tflite)
    lines = [
        "// Generated by ml/board_test/make_smoke_model.py — do not edit by hand.",
        "#pragma once",
        "",
        "#ifdef __has_attribute",
        "#define HAVE_ATTRIBUTE(x) __has_attribute(x)",
        "#else",
        "#define HAVE_ATTRIBUTE(x) 0",
        "#endif",
        "#if HAVE_ATTRIBUTE(aligned) || (defined(__GNUC__) && !defined(__clang__))",
        "#define DATA_ALIGN_ATTRIBUTE __attribute__((aligned(4)))",
        "#else",
        "#define DATA_ALIGN_ATTRIBUTE",
        "#endif",
        "",
        "#define TF_NUM_OPS 2",
        "#define TF_NUM_INPUTS 4",
        "#define TF_NUM_OUTPUTS 3",
        "#define TF_OP_FULLYCONNECTED",
        "#define TF_OP_SOFTMAX",
        "",
        f"// {n} pre-normalised test samples (features: {', '.join(FEATURES)})",
        f"// classes: 0={CLASSES[0]}, 1={CLASSES[1]}, 2={CLASSES[2]}",
        f"const int N_SAMPLES = {n};",
        "float SAMPLES[N_SAMPLES][4] = {",
        *[f"  {{{c_floats(s)}}}," for s in samples],
        "};",
        "const int EXPECTED_CLASS[N_SAMPLES] = {" + ", ".join(map(str, expected_cls)) + "};",
        "const float EXPECTED_PROB[N_SAMPLES][3] = {",
        *[f"  {{{c_floats(p)}}}," for p in expected_prob],
        "};",
        "",
        f"/** model size = {len(tflite)} bytes **/",
        f"const unsigned int smokeModelLen = {len(tflite)};",
        f"const unsigned char smokeModel[] DATA_ALIGN_ATTRIBUTE = {{ {body} }};",
        "",
    ]
    out_path = os.path.join(_HERE, "tflm_smoke", "sketch", "model.h")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    open(out_path, "w").write("\n".join(lines))
    with open(os.path.join(_HERE, "tflm_smoke", "smoke_model.tflite"), "wb") as f:
        f.write(tflite)
    print(f"Wrote {out_path} ({n} samples)")


if __name__ == "__main__":
    main()
