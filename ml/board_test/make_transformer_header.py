#!/usr/bin/env python3
"""Write ml/board_test/tflm_transformer/sketch/model.h for the real transformer (float32 TFLite).

Takes model_float32.tflite from ml/keras_tf/convert_tflite.py, picks real chronological-test rows
(2 correctly classified per class + 2 the model gets wrong, so the board must reproduce the
mistakes too), runs them through the Mac's TFLite reference kernels and stores inputs, expected
class and expected probabilities. Also emits the op list so the sketch can register exactly
those ops (no TF_OP_* macros, so EloquentTinyML's begin() does not register any twice).

Usage:
  .venv/bin/python ml/board_test/make_transformer_header.py data-local/datasets/sept15.jsonl
"""

from __future__ import annotations

import os
import sys

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")

import numpy as np  # noqa: E402
import tensorflow as tf  # noqa: E402

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_HERE, ".."))
from common.data import CLASS_NAMES, load_split  # noqa: E402

# TFLite op name -> MicroMutableOpResolver method
RESOLVER = {
    "ADD": "AddAdd", "CAST": "AddCast", "CONCATENATION": "AddConcatenation",
    "FULLY_CONNECTED": "AddFullyConnected", "GATHER": "AddGather", "MEAN": "AddMean", "MUL": "AddMul",
    "PACK": "AddPack", "RESHAPE": "AddReshape", "RSQRT": "AddRsqrt", "SOFTMAX": "AddSoftmax",
    "SQUARED_DIFFERENCE": "AddSquaredDifference", "STRIDED_SLICE": "AddStridedSlice", "SUB": "AddSub",
    "SUM": "AddSum",
}


def f(v) -> str:
    return ", ".join(f"{float(x):.8f}f" for x in v)


def main() -> None:
    dataset = sys.argv[1]
    name = os.path.basename(dataset).replace(".jsonl", "")
    tfl_path = os.path.join(_HERE, "..", "artifacts", name, "tensorflow", "model_float32.tflite")
    tflite = open(tfl_path, "rb").read()
    d = load_split(dataset)
    X, y = d["X_test"].astype(np.float32), d["y_test"]

    it = tf.lite.Interpreter(model_content=tflite,
                             experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_REF)
    it.allocate_tensors()
    ops = sorted({o["op_name"] for o in it._get_ops_details()})
    unknown = [o for o in ops if o not in RESOLVER]
    if unknown:
        raise SystemExit(f"no resolver mapping for {unknown}; extend RESOLVER")
    inp, out = it.get_input_details()[0], it.get_output_details()[0]

    def run(row):
        it.set_tensor(inp["index"], row[None, :])
        it.invoke()
        return it.get_tensor(out["index"])[0].copy()

    rng = np.random.default_rng(0)
    picks = []  # (row, true, pred, probs)
    for c in range(3):
        n = 0
        for j in rng.permutation(np.where(y == c)[0])[:500]:
            p = run(X[j])
            if p.argmax() == c:
                picks.append((X[j], c, int(p.argmax()), p)); n += 1
            if n == 2:
                break
    wrong = 0
    for j in rng.permutation(len(y))[:5000]:
        p = run(X[j])
        if p.argmax() != y[j]:
            picks.append((X[j], int(y[j]), int(p.argmax()), p)); wrong += 1
        if wrong == 2:
            break

    n = len(picks)
    body = ", ".join(f"0x{b:02x}" for b in tflite)
    lines = [
        "// Generated by ml/board_test/make_transformer_header.py — do not edit by hand.",
        f"// Model: {os.path.relpath(tfl_path, os.path.join(_HERE, '..', '..'))} ({len(tflite)} bytes, float32, 1,155 params)",
        "#pragma once",
        "",
        "#ifdef __has_attribute",
        "#define HAVE_ATTRIBUTE(x) __has_attribute(x)",
        "#else",
        "#define HAVE_ATTRIBUTE(x) 0",
        "#endif",
        "#if HAVE_ATTRIBUTE(aligned) || (defined(__GNUC__) && !defined(__clang__))",
        "#define DATA_ALIGN_ATTRIBUTE __attribute__((aligned(16)))",
        "#else",
        "#define DATA_ALIGN_ATTRIBUTE",
        "#endif",
        "",
        f"#define TF_NUM_OPS {len(ops)}",
        "#define TF_NUM_INPUTS 4",
        "#define TF_NUM_OUTPUTS 3",
        "// No TF_OP_* macros on purpose: the sketch registers every op below exactly once.",
        "#define REGISTER_MODEL_OPS(resolver) \\",
        *[f"  resolver.{RESOLVER[o]}(); \\" for o in ops],
        "  do {} while (0)",
        "",
        f"// classes: 0={CLASS_NAMES[0]}, 1={CLASS_NAMES[1]}, 2={CLASS_NAMES[2]}",
        "// inputs are quantile-bin ids (0..15) for rsmi, light_delta, gas_index_trend, rsmi_trend",
        f"const int N_SAMPLES = {n};",
        "float SAMPLES[N_SAMPLES][4] = {",
        *[f"  {{{f(r)}}},  // true {t}" for r, t, _, _ in picks],
        "};",
        "const int TRUE_CLASS[N_SAMPLES] = {" + ", ".join(str(t) for _, t, _, _ in picks) + "};",
        "const int EXPECTED_CLASS[N_SAMPLES] = {" + ", ".join(str(p) for _, _, p, _ in picks) + "};",
        "const float EXPECTED_PROB[N_SAMPLES][3] = {",
        *[f"  {{{f(pr)}}}," for _, _, _, pr in picks],
        "};",
        "",
        f"/** model size = {len(tflite)} bytes **/",
        f"const unsigned int transformerModelLen = {len(tflite)};",
        f"const unsigned char transformerModel[] DATA_ALIGN_ATTRIBUTE = {{ {body} }};",
        "",
    ]
    out_path = os.path.join(_HERE, "tflm_transformer", "sketch", "model.h")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    open(out_path, "w").write("\n".join(lines))
    print(f"ops ({len(ops)}): {ops}")
    print(f"Wrote {out_path}: {n} samples ({n - wrong} correct, {wrong} deliberately wrong), {len(tflite)} bytes")


if __name__ == "__main__":
    main()
